import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import Boolean, Computed, ForeignKey, Numeric, Text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, timestamp_now, uuid_pk


class EligibilityCheck(Base):
    __tablename__ = "eligibility_checks"

    id: Mapped[uuid.UUID] = uuid_pk()
    solution_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("solution_abstracts.id", ondelete="CASCADE")
    )
    dpiit_ok: Mapped[bool | None] = mapped_column(Boolean)
    turnover_ok: Mapped[bool | None] = mapped_column(Boolean)
    domain_ok: Mapped[bool | None] = mapped_column(Boolean)
    trl_ok: Mapped[bool | None] = mapped_column(Boolean)
    # Generated by Postgres — Computed tells the ORM never to write it, only read it back.
    overall_eligible: Mapped[bool | None] = mapped_column(
        Boolean, Computed("dpiit_ok AND turnover_ok AND domain_ok AND trl_ok", persisted=True)
    )
    # [{rule, status, reason}] for every rule — see app/services/eligibility.py.
    rule_results: Mapped[list | None] = mapped_column(JSONB)
    checked_at: Mapped[datetime | None] = timestamp_now()


class Evaluation(Base):
    __tablename__ = "evaluations"

    id: Mapped[uuid.UUID] = uuid_pk()
    solution_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("solution_abstracts.id", ondelete="CASCADE")
    )
    evaluator_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"))
    technical_merit: Mapped[Decimal | None] = mapped_column(Numeric)  # 0-30
    cost_realism: Mapped[Decimal | None] = mapped_column(Numeric)  # 0-20
    team_capability: Mapped[Decimal | None] = mapped_column(Numeric)  # 0-20
    timeline_viability: Mapped[Decimal | None] = mapped_column(Numeric)  # 0-30
    total_score: Mapped[Decimal | None] = mapped_column(
        Numeric,
        Computed("technical_merit + cost_realism + team_capability + timeline_viability", persisted=True),
    )
    comments: Mapped[str | None] = mapped_column(Text)
    evaluated_at: Mapped[datetime | None] = timestamp_now()
